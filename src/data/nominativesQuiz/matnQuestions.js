function matnCloze({
  chapterId,
  topicId,
  lineIdx,
  blank,
  distractors,
  prompt,
  explanation,
  suffix = "",
}) {
  const line = chapterLine(chapterId, lineIdx);
  const meta = topicMeta(chapterId, topicId);
  const options = [
    option("ok", blank, "from the matn"),
    ...distractors.map((item, index) => option(`d${index}`, item.ar, item.en)),
  ];
  return cloze({
    id: `${chapterId}-matn-${lineIdx}-cloze${suffix}`,
    chapterId,
    track: "matn",
    ...meta,
    prompt: prompt || "Fill the blank with the exact wording of the matn.",
    stemAr: stemWithBlank(line.ar, blank),
    stemEn: line.en,
    options,
    answer: "ok",
    explanation,
  });
}

function matnRecall({ chapterId, topicId, lineIdx, excerpt, prompt, explanation, suffix = "" }) {
  const line = chapterLine(chapterId, lineIdx);
  const source = excerpt || line.ar;
  const meta = topicMeta(chapterId, topicId);
  const tokens = tokenizeAr(source).map((ar, index) => ({ id: `t${index}`, ar }));
  return recall({
    id: `${chapterId}-matn-${lineIdx}-recall${suffix}`,
    chapterId,
    ...meta,
    prompt: prompt || "Rebuild this matn line in the exact order.",
    stemEn: line.en,
    tokens,
    correctOrder: tokens.map((token) => token.id),
    explanation,
  });
}

