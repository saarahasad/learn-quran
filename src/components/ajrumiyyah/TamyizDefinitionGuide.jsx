  <div class="dcm-word-def">Original: <span class="dcm-ar">مَالِي أَكْثَرُ مِنْ مَالِكَ</span> — "My wealth is greater than your wealth." <span class="dcm-ar">مَال</span> is dropped. The possessor is the attached yā of "my," and an attached pronoun cannot start the sentence, so it stands up as the detached <span class="dcm-ar">أَنَا</span>. Wealth then returns as the tamyīz. Al-Kahf 34:</div>
