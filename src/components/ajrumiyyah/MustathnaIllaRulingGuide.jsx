  <tr><td class="dcm-td-ar">مَا ضَرَبْتُ إِلَّا زَيْدًا</td><td class="dcm-td-ar">زَيْدًا</td><td class="dcm-td-ar">ضَرَبْتُ</td><td><span class="dcm-ar">مَفْعُول بِه</span>, <span class="dcm-ar">مَنْصُوب</span> (fatḥah)</td></tr>
