/**
 * Parse iraab HTML exports into src/data/baqarahIraab.js
 * Usage: node scripts/parse-baqarah-iraab.mjs [file-or-dir ...]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "src/data/baqarahIraab.js");

const BADGE_KIND = {
  "badge-harf": "harf",
  "badge-ism": "ism",
  "badge-fil": "fil",
  "badge-jumlah": "jumlah",
};

function innerHtml(html) {
  if (!html) return "";
  return html.replace(/\s+/g, " ").trim();
}

function textContent(html) {
  if (!html) return "";
  return html.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
}

function parseAyahSection(sectionHtml) {
  const cardStart = sectionHtml.indexOf('<div class="ayah-card">');
  if (cardStart === -1) return null;

  const cardInnerStart = cardStart + '<div class="ayah-card">'.length;
  const tableStart = sectionHtml.indexOf('<div class="table-wrap">', cardInnerStart);
  if (tableStart === -1) return null;

  const card = sectionHtml.slice(cardInnerStart, tableStart);
  const label = card.match(/<div class="ayah-label">([\s\S]*?)<\/div>/)?.[1]?.trim() ?? "";
  const verseMatch = label.match(/[ĀA]yah\s+(\d+)/i);
  const verse = verseMatch ? Number(verseMatch[1]) : null;

  const text = textContent(
    card.match(/<div class="ayah-text">([\s\S]*?)<\/div>/)?.[1],
  );
  const translation = textContent(
    card.match(/<div class="ayah-ref">([\s\S]*?)<\/div>/)?.[1],
  );

  const tbody = sectionHtml.match(/<tbody>([\s\S]*?)<\/tbody>/)?.[1] ?? "";
  const rowMatches = [...tbody.matchAll(/<tr>([\s\S]*?)<\/tr>/g)];

  const rows = rowMatches.map((match) => {
    const row = match[1];
    const word = textContent(row.match(/<td class="word">([\s\S]*?)<\/td>/)?.[1]);
    const typeCell = row.match(/<td class="type">([\s\S]*?)<\/td>/)?.[1] ?? "";
    const badgeClass =
      typeCell.match(/badge-(harf|ism|fil|jumlah)/)?.[0] ?? "badge-ism";
    const typeLabel = textContent(typeCell.match(/<span class="badge[^"]*">([\s\S]*?)<\/span>/)?.[1]);
    const arHtml = innerHtml(row.match(/<td class="ar-exp">([\s\S]*?)<\/td>/)?.[1]);
    const enHtml = innerHtml(row.match(/<td class="en-exp">([\s\S]*?)<\/td>/)?.[1]);

    return {
      word,
      typeLabel,
      typeKind: BADGE_KIND[badgeClass] ?? "ism",
      arHtml,
      enHtml,
    };
  });

  return { verse, text, translation, rows };
}

function parseFile(filePath) {
  const html = fs.readFileSync(filePath, "utf8");

  if (html.includes('class="ayah-section"')) {
    const chunks = html.split(/<div class="ayah-section">/).slice(1);
    return chunks
      .map((chunk) => parseAyahSection(chunk))
      .filter(Boolean);
  }

  const single = parseAyahSection(html);
  return single ? [single] : [];
}

const PAGE_SOURCES = [
  {
    page: 3,
    paths: [
      path.join(process.env.HOME ?? "", "Downloads/iraab-baqarah-6.html"),
      path.join(process.env.HOME ?? "", "Downloads/iraab-baqarah-7.html"),
      path.join(process.env.HOME ?? "", "Downloads/iraab-baqarah-8.html"),
      path.join(process.env.HOME ?? "", "Downloads/iraab-baqarah-9.html"),
      path.join(process.env.HOME ?? "", "Downloads/iraab-baqarah-10-14.html"),
      path.join(process.env.HOME ?? "", "Downloads/iraab-baqarah-15-16.html"),
    ],
  },
  {
    page: 4,
    paths: [path.join(ROOT, "scripts/iraab-input/iraab-baqarah-17-24.html")],
  },
];

function collectAyahs(paths) {
  const byVerse = new Map();
  for (const input of paths) {
    if (!fs.existsSync(input)) {
      console.warn(`Skip missing: ${input}`);
      continue;
    }
    for (const ayah of parseFile(input)) {
      byVerse.set(ayah.verse, ayah);
    }
  }
  return [...byVerse.values()].sort((a, b) => a.verse - b.verse);
}

function main() {
  const byPage = {};

  if (process.argv.length > 2) {
    const pageArg = process.argv.find((arg) => arg.startsWith("--page="));
    const page = pageArg ? Number(pageArg.split("=")[1]) : null;
    const files = process.argv.filter((arg) => !arg.startsWith("--"));
    if (!page || !files.length) {
      console.error("Usage: node parse-baqarah-iraab.mjs --page=N file.html [...]");
      process.exit(1);
    }
    byPage[page] = collectAyahs(files);
  } else {
    for (const { page, paths } of PAGE_SOURCES) {
      const ayahs = collectAyahs(paths);
      if (ayahs.length) byPage[page] = ayahs;
    }
  }

  const ayahCount = Object.values(byPage).reduce((sum, list) => sum + list.length, 0);

  const out = `/**
 * Iʿrāb tables for Al-Baqarah page guides.
 * Generated by scripts/parse-baqarah-iraab.mjs — do not edit by hand.
 */
export const BAQARAH_IRAAB_BY_PAGE = ${JSON.stringify(byPage, null, 2)};

export function getBaqarahIraabForPage(mushafPage) {
  return BAQARAH_IRAAB_BY_PAGE[mushafPage] ?? null;
}

export function hasBaqarahIraabForPage(mushafPage) {
  return Boolean(BAQARAH_IRAAB_BY_PAGE[mushafPage]?.length);
}
`;

  fs.writeFileSync(OUT, out);
  const pages = Object.keys(byPage).sort((a, b) => Number(a) - Number(b)).join(", ");
  console.log(`Wrote ${ayahCount} āyāt (pages ${pages}) → ${OUT}`);
}

main();
