LATIN_TO_AR = {
    "a": "ا", "b": "ب", "d": "د", "f": "ف", "h": "ه", "i": "ي", "j": "ج",
    "k": "ك", "l": "ل", "m": "م", "n": "ن", "o": "و", "q": "ق", "r": "ر",
    "s": "س", "t": "ت", "u": "ُ", "w": "و", "y": "ي", "z": "ز",
}


def has_arabic(s):
    return any("\u0600" <= c <= "\u06FF" for c in s)


def fix_mixed(s):
    if not has_arabic(s):
        return s
    out = []
    for c in s:
        if c.isascii() and c.isalpha() and c.lower() in LATIN_TO_AR:
            out.append(LATIN_TO_AR[c.lower()])
        else:
            out.append(c)
    return "".join(out)


def repl(m):
    s = m.group(1)
    if has_arabic(s):
        return '"' + fix_mixed(s) + '"'
    return m.group(0)


