/**
 * Parse plain-text iʿrāb (﴿word﴾: explanation) into baqarahIraab row objects.
 * Usage: node scripts/parse-plain-baqarah-iraab.mjs <file.txt> [--merge-page=9]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const IRAAB_OUT = path.join(ROOT, "src/data/baqarahIraab.js");

const TERM_RE =
  /(مَرْفُوع|مَنْصُوب|مَجْرُور|مَجْزُوم|مَبْنِي|فَاعِل|مَفْعُول|خَبَر|مُبْتَدَأ|مُضَاف|حَال|بَدَل|نَائِب|صِلَة|مَعْطُوف|نَعْت|تَمْيِيز|ظَرْف|حَرْف|فِعْل|اسْم|ضَمِير|جُمْلَة)/g;

function wrapTerms(text) {
  return text.replace(TERM_RE, '<span class="term">$1</span>');
}

function inferTypeKind(text) {
  if (/صِلَةُ الْمَوْصُول|جُمْلَةُ|شِبْهُ الْجُمْلَة/.test(text)) return "jumlah";
  if (/فِعْل|فعل/.test(text)) return "fil";
  if (/حَرْف|حرف/.test(text)) return "harf";
  return "ism";
}

function inferTypeLabel(text) {
  const checks = [
    [/فِعْلُ أَمْر|فعل أمر/, "فعل أمر"],
    [/فِعْلٌ مُضَارِع|فعل مضارع/, "فعل مضارع"],
    [/فِعْلٌ مَاضٍ|فعل ماض/, "فعل ماضٍ"],
    [/اسْمٌ مَوْصُول|اسم موصول/, "اسم موصول"],
    [/اسْمُ إِشَارَة/, "اسم إشارة"],
    [/حَرْفُ جَر|حرف جر/, "حرف جر"],
    [/حَرْفُ عَطْف/, "حرف عطف"],
    [/نَائِبُ فَاعِل/, "نائب فاعل"],
    [/فَاعِل/, "فاعل"],
    [/مَفْعُول/, "مفعول"],
    [/خَبَر/, "خبر"],
    [/مُبْتَدَأ/, "مبتدأ"],
    [/بَدَل/, "بدل"],
    [/حَال/, "حال"],
    [/نَعْت/, "نعت"],
    [/مَعْطُوف/, "معطوف"],
    [/تَمْيِيز/, "تمييز"],
    [/ظَرْف/, "ظرف"],
    [/مُضَاف/, "مضاف"],
    [/ضَمِير/, "ضمير"],
    [/جُزْءٌ عَدَدِي/, "عدد"],
    [/صِلَة/, "جملة"],
  ];
  for (const [re, label] of checks) {
    if (re.test(text)) return label;
  }
  if (/حَرْف|حرف/.test(text)) return "حرف";
  if (/فِعْل|فعل/.test(text)) return "فعل";
  return "اسم";
}

function buildEnHtml(word, arPlain) {
  const role = inferTypeLabel(arPlain);
  return `<strong>${word}</strong> — ${role} (${arPlain.slice(0, 120)}${arPlain.length > 120 ? "…" : ""})`;
}

function parsePlainFile(filePath) {
  const raw = fs.readFileSync(filePath, "utf8");
  const lines = raw.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const ayahs = [];
  let current = null;

  for (const line of lines) {
    const verseMatch = line.match(/\((\d+)\)\s*$/);
    if (verseMatch && line.includes(" ") && !line.startsWith("﴿")) {
      if (current?.rows.length) ayahs.push(current);
      const verse = Number(verseMatch[1]);
      const text = line.replace(/\s*\(\d+\)\s*$/, "").trim();
      current = { verse, text, translation: "", rows: [] };
      continue;
    }

    const wordMatch = line.match(/^﴿(.+?)﴾:\s*(.+)$/);
    if (wordMatch && current) {
      const word = wordMatch[1].trim();
      const arPlain = wordMatch[2].trim();
      current.rows.push({
        word,
        typeLabel: inferTypeLabel(arPlain),
        typeKind: inferTypeKind(arPlain),
        arHtml: wrapTerms(arPlain),
        enHtml: buildEnHtml(word, arPlain),
      });
    }
  }

  if (current?.rows.length) ayahs.push(current);
  return ayahs;
}

function loadExistingByPage() {
  if (!fs.existsSync(IRAAB_OUT)) return {};
  const src = fs.readFileSync(IRAAB_OUT, "utf8");
  const match = src.match(/export const BAQARAH_IRAAB_BY_PAGE = (\{[\s\S]*?\n\});/);
  if (!match) return {};
  return JSON.parse(match[1]);
}

function writeIraabFile(byPage) {
  const out = `/**
 * Iʿrāb tables for Al-Baqarah page guides.
 * Generated by scripts/parse-baqarah-iraab.mjs — do not edit by hand.
 */
export const BAQARAH_IRAAB_BY_PAGE = ${JSON.stringify(byPage, null, 2)};

export function getBaqarahIraabForPage(mushafPage) {
  return BAQARAH_IRAAB_BY_PAGE[mushafPage] ?? null;
}

export function hasBaqarahIraabForPage(mushafPage) {
  return Boolean(BAQARAH_IRAAB_BY_PAGE[mushafPage]?.length);
}
`;
  fs.writeFileSync(IRAAB_OUT, out);
}

function main() {
  const mergePage = process.argv.find((a) => a.startsWith("--merge-page="));
  const page = mergePage ? String(Number(mergePage.split("=")[1])) : null;
  const file = process.argv.find((a) => !a.startsWith("--") && a.endsWith(".txt"));

  if (!file) {
    console.error("Usage: node parse-plain-baqarah-iraab.mjs file.txt [--merge-page=9]");
    process.exit(1);
  }

  const ayahs = parsePlainFile(path.resolve(file));
  console.log(`Parsed ${ayahs.length} āyāt (${ayahs.map((a) => a.verse).join(", ")})`);

  if (page) {
    const byPage = loadExistingByPage();
    byPage[page] = ayahs;
    writeIraabFile(byPage);
    console.log(`Merged page ${page} → ${IRAAB_OUT}`);
  } else {
    console.log(JSON.stringify(ayahs, null, 2));
  }
}

main();
